#!/usr/bin/env bash
#
# Wingman SessionStart hook — injects LIVE repo status into context.
#
# WHY THIS EXISTS:
# On 2026-07-30 both Current Sprint.md and MEMORY.md asserted that branch
# feat/design-tokens was "17 commits ahead and UNPUSHED". It had merged as PR #58
# and shipped. A session opening on that prose would have told Sebastian to push
# work that was already live. Hand-typed status rots; this reads the truth every
# time instead.
#
# DESIGN RULES:
#  - NEVER block or slow a session. Every command is timeout-wrapped and every
#    failure degrades to a note, not an error. Worst case you get less info.
#  - Releases live in the SEPARATE PUBLIC repo bandidoseb/wingman-releases. A bare
#    `gh release view` reads the source repo and reports a version several releases
#    stale — that exact bug sat in CLAUDE.md for a month.
#  - Output goes to stdout, which Claude Code adds to the session context.

cd "$CLAUDE_PROJECT_DIR" 2>/dev/null || exit 0
command -v git >/dev/null 2>&1 || exit 0

# `timeout` is not on macOS by default; fall back to gtimeout, then to running bare.
if command -v timeout >/dev/null 2>&1;  then TO="timeout"
elif command -v gtimeout >/dev/null 2>&1; then TO="gtimeout"
else TO=""; fi
run() { local secs=$1; shift; if [ -n "$TO" ]; then $TO "$secs" "$@" 2>/dev/null; else "$@" 2>/dev/null; fi; }

branch=$(git branch --show-current 2>/dev/null)
head=$(git log -1 --format='%h %s' 2>/dev/null | cut -c1-100)
dirty=$(git status --porcelain 2>/dev/null | wc -l | tr -d ' ')
version=$(node -p "require('./package.json').version" 2>/dev/null)

echo "## Live repo status (generated by the SessionStart hook — trust this over any prose)"
echo
echo "- **Branch:** \`${branch:-unknown}\` · **HEAD:** ${head:-unknown}"
echo "- **Working tree:** $( [ "$dirty" = "0" ] && echo "clean" || echo "**$dirty uncommitted file(s)**" )"
echo "- **package.json version:** ${version:-unknown}"

# Ahead/behind vs the remote tracking branch — the number people get wrong by hand.
upstream=$(git rev-parse --abbrev-ref --symbolic-full-name '@{u}' 2>/dev/null)
if [ -n "$upstream" ]; then
  counts=$(git rev-list --left-right --count "$upstream"...HEAD 2>/dev/null)
  behind=$(echo "$counts" | awk '{print $1}')
  ahead=$(echo "$counts" | awk '{print $2}')
  echo "- **vs \`$upstream\`:** ${ahead:-0} ahead, ${behind:-0} behind"
else
  echo "- **Upstream:** none set for this branch (never pushed, or local-only)"
fi

if command -v gh >/dev/null 2>&1; then
  prs=$(run 8 gh pr list --state merged --limit 3 --json number,title \
        --template '{{range .}}#{{.number}} {{.title}}{{"\n"}}{{end}}')
  if [ -n "$prs" ]; then
    echo "- **Recently merged PRs:**"
    echo "$prs" | while IFS= read -r l; do [ -n "$l" ] && echo "  - $(echo "$l" | cut -c1-90)"; done
  fi

  openpr=$(run 8 gh pr list --head "$branch" --state open --json number,title \
           --template '{{range .}}#{{.number}} {{.title}}{{end}}')
  [ -n "$openpr" ] && echo "- **Open PR for this branch:** $openpr"

  rel=$(run 8 gh release list --repo bandidoseb/wingman-releases --limit 1 \
        --json tagName,isLatest --template '{{range .}}{{.tagName}}{{end}}')
  [ -n "$rel" ] && echo "- **Latest published release:** $rel (repo: bandidoseb/wingman-releases)"
fi

echo
echo "**If any file's prose disagrees with the above, the above wins — say so out loud.**"
echo "Read \`context/STATE.md\` (generated) and \`Wingman Brain/01 - Build Log/NOW.md\` next."
exit 0
